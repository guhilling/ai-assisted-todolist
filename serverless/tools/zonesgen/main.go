// Command zonesgen writes the names of the time zones a task may be given (#474) into a Go file:
// every zone in the tzdata of the Go toolchain building it, which is also the tzdata cmd/api
// embeds (time/tzdata).
//
// A list, rather than asking time.LoadLocation whether a name loads, because LoadLocation reads
// the system's zone files first: on macOS's disk, which ignores case, it loads "europe/berlin",
// which the Quarkus backend refuses. Generated from the toolchain's own zoneinfo.zip, the list
// changes only with a Go release that brings new tzdata: Serverless CI's drift check then fails
// until go generate is run with the go.mod version.
//
//	go run ./tools/zonesgen <output.go>
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

// main writes the zone list to the file named by its one argument.
func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: zonesgen <output.go>")
		os.Exit(2)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "zonesgen:", err)
		os.Exit(1)
	}
}

// gorootOf is the toolchain's root: $GOROOT, which go generate sets to the go command that
// invoked it, or else what that command says.
func gorootOf() (string, error) {
	if root := os.Getenv("GOROOT"); root != "" {
		return root, nil
	}
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return "", fmt.Errorf("finding GOROOT: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}

// run reads the toolchain's zoneinfo.zip and writes the Go file listing its zone names.
func run(output string) error {
	goroot, err := gorootOf()
	if err != nil {
		return err
	}
	z, err := zip.OpenReader(filepath.Join(goroot, "lib", "time", "zoneinfo.zip"))
	if err != nil {
		return err
	}
	defer z.Close()
	var names []string
	for _, f := range z.File {
		if !strings.HasSuffix(f.Name, "/") {
			names = append(names, f.Name)
		}
	}
	slices.Sort(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/zonesgen from the Go toolchain's tzdata. DO NOT EDIT.\n\n")
	b.WriteString("package board\n\n")
	b.WriteString("// tzdataZones is every zone name in the tzdata cmd/api embeds, exactly as written.\n")
	b.WriteString("var tzdataZones = map[string]bool{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: true,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(output, src, 0o644)
}
