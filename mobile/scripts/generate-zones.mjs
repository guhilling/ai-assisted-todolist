/**
 * Writes `src/zones.ts`, the time zones the app's zone picker offers (#477).
 *
 * Hermes cannot be relied on to list zones through `Intl`, so the list is taken from Node's, the
 * same tzdata the website's browsers carry, and committed. The `Etc/` zones are left out: they
 * are fixed offsets, which the backend refuses; `UTC` is added. Run it again when the list should
 * follow newer tzdata: `node scripts/generate-zones.mjs`.
 */
import { writeFileSync } from 'node:fs'

/**
 * ICU keeps some zones under the names they had before IANA renamed them, which is what people
 * search for; the backend takes both. The renames since ICU froze its names.
 */
const RENAMED = {
  'Africa/Asmera': 'Africa/Asmara',
  'America/Buenos_Aires': 'America/Argentina/Buenos_Aires',
  'America/Catamarca': 'America/Argentina/Catamarca',
  'America/Coral_Harbour': 'America/Atikokan',
  'America/Cordoba': 'America/Argentina/Cordoba',
  'America/Godthab': 'America/Nuuk',
  'America/Indianapolis': 'America/Indiana/Indianapolis',
  'America/Jujuy': 'America/Argentina/Jujuy',
  'America/Louisville': 'America/Kentucky/Louisville',
  'America/Mendoza': 'America/Argentina/Mendoza',
  'Asia/Calcutta': 'Asia/Kolkata',
  'Asia/Katmandu': 'Asia/Kathmandu',
  'Asia/Rangoon': 'Asia/Yangon',
  'Asia/Saigon': 'Asia/Ho_Chi_Minh',
  'Atlantic/Faeroe': 'Atlantic/Faroe',
  'Europe/Kiev': 'Europe/Kyiv',
  'Pacific/Enderbury': 'Pacific/Kanton',
  'Pacific/Ponape': 'Pacific/Pohnpei',
  'Pacific/Truk': 'Pacific/Chuuk',
}

// The same rule as `offerable` in frontend/src/dueTime.ts, which a Node script cannot import:
// regions' zones only, no Etc/ offsets. Node lists UTC under no name of its own; it is added.
const regions = Intl.supportedValuesOf('timeZone')
  .filter((zone) => zone.includes('/') && !zone.startsWith('Etc/'))
  .map((zone) => RENAMED[zone] ?? zone)
const zones = [...new Set([...regions, 'UTC'])].sort()
const lines = zones.map((zone) => `  '${zone}',`).join('\n')
writeFileSync(
  new URL('../src/zones.ts', import.meta.url),
  `/**
 * The time zones a task can be tied to in the app (#477), by IANA name. Generated by
 * \`scripts/generate-zones.mjs\` from Node's tzdata, since Hermes' \`Intl\` cannot be relied on to
 * list them; do not edit by hand.
 */
export const timeZones: readonly string[] = [
${lines}
]
`,
)
console.log(`wrote ${zones.length} zones to src/zones.ts`)
