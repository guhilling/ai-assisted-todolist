/**
 * Writes `src/zones.ts`, the time zones the app's zone picker offers (#477).
 *
 * Hermes cannot be relied on to list zones through `Intl`, so the list is taken from Node's, the
 * same tzdata the website's browsers carry, and committed. The `Etc/` zones are left out: they
 * are fixed offsets, which the backend refuses; `UTC` is added. Run it again when the list should
 * follow newer tzdata: `node scripts/generate-zones.mjs`.
 */
import { writeFileSync } from 'node:fs'

// Node lists UTC under no name of its own; it is offered by it, as the website does.
const regions = Intl.supportedValuesOf('timeZone').filter(
  (zone) => zone.includes('/') && !zone.startsWith('Etc/'),
)
const zones = [...regions, 'UTC'].sort()
const lines = zones.map((zone) => `  '${zone}',`).join('\n')
writeFileSync(
  new URL('../src/zones.ts', import.meta.url),
  `/**
 * The time zones a task can be tied to in the app (#477), by IANA name. Generated by
 * \`scripts/generate-zones.mjs\` from Node's tzdata, since Hermes' \`Intl\` cannot be relied on to
 * list them; do not edit by hand.
 */
export const timeZones: readonly string[] = [
${lines}
]
`,
)
console.log(`wrote ${zones.length} zones to src/zones.ts`)
